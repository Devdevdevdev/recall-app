// Phase 16.16A: generate the rollback-only production validation suite.
//
// Output: supabase/test-fixtures/phase-16-16a-rollback-validation.sql (NOT under
// supabase/tests/, so the local `supabase test db` never re-runs its DDL). It is
// BEGIN -> the exact migration body (its own begin/commit removed) -> targeted
// assertions against the real production rows -> ROLLBACK. Run it only through
// `npm run test:remote-pgtap -- --file <output>`, which injects a transient pgTAP
// after BEGIN and verifies afterwards that pgTAP is absent and no session is idle
// in a transaction. Nothing is committed; the migration never enters history.
//
// Deliberately excluded: any call that inserts an observation (the 9-argument gate
// consumes observation_seq, and sequence advances survive ROLLBACK). Replay is
// proven locally on the same six payload hashes (scripts/verify-phase-16-16a-local.mjs).
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

export const MIGRATION =
  'supabase/migrations/20260926210000_phase_16_16_quarantine_payload_retention.sql';
export const ATTACHMENT = 'docs/phase-16-16a-payload-attachment-manifest.json';
export const OUTPUT = 'supabase/test-fixtures/phase-16-16a-rollback-validation.sql';

export function migrationBody(sql) {
  const lines = sql.split('\n');
  const begin = lines.findIndex((line) => line.trim() === 'begin;');
  const commit = lines.findLastIndex((line) => line.trim() === 'commit;');
  if (begin < 0 || commit <= begin) throw new Error('Migration must be wrapped in begin/commit.');
  return lines.slice(begin + 1, commit).join('\n');
}

export async function buildSuite() {
  const migration = await readFile(MIGRATION, 'utf8');
  const attachmentText = await readFile(ATTACHMENT, 'utf8');
  const attachment = JSON.parse(attachmentText);
  const body = migrationBody(migration);
  if (attachmentText.includes('$attach$')) throw new Error('Unsafe attachment literal.');
  const six = attachment.items
    .map((i) => `('${i.apiId}','${i.recallNumber}','${i.payloadSha256}')`)
    .join(',\n  ');
  return `-- GENERATED by scripts/build-phase-16-16a-rollback-validation.mjs. Do not edit.
-- Migration: ${MIGRATION}
-- Migration SHA-256: ${createHash('sha256').update(migration).digest('hex')}
-- Attachment SHA-256: ${createHash('sha256').update(attachmentText).digest('hex')}
-- ROLLBACK-ONLY production compatibility validation for Phase 16.16A.
begin;
set local lock_timeout = '3s';
set local statement_timeout = '60s';
set local idle_in_transaction_session_timeout = '120s';
set local search_path = extensions, public, auth;

-- Pre-migration state, captured inside the transaction.
create temporary table v16a_before on commit drop as select
  (select md5(p.prosrc) from pg_proc p
    where p.oid = 'public.record_cpsc_identity_observation(text,text,text,text,text,date,text,timestamptz,text)'::regprocedure) as legacy_gate_md5,
  (select count(*) from private.cpsc_identity_observations) as observations,
  (select md5(string_agg(o::text, '|' order by o.id)) from private.cpsc_identity_observations o) as observations_md5,
  (select md5(string_agg(i::text, '|' order by i.id)) from private.cpsc_source_identities i) as identities_md5,
  (select md5(string_agg(a::text, '|' order by a.id)) from private.cpsc_source_aliases a) as aliases_md5,
  (select md5(string_agg(r::text, '|' order by r.id)) from private.cpsc_api_revisions r) as api_revisions_md5,
  (select md5(string_agg(n::text, '|' order by n.id)) from public.recall_notices n) as notices_md5,
  (select md5(string_agg(s::text, '|' order by s.source_id)) from private.recall_source_sync_state s) as sync_md5,
  private.cpsc_historical_rows_digest((select id from public.recall_sources where source_key = 'cpsc')) as historical_digest;
create temporary table v16a_six (api text, num text, hash text) on commit drop;
insert into v16a_six values
  ${six};

-- ===== BEGIN exact migration body =====
${body}
-- ===== END exact migration body =====

select extensions.no_plan();

-- Schema and privileges on the real database.
select extensions.ok(to_regclass(t) is not null, format('%s created', t))
  from unnest(array['private.cpsc_observation_payloads','private.cpsc_observation_sightings',
    'private.cpsc_observation_payload_retention']) t;
select extensions.ok(c.relrowsecurity, format('RLS on %s', c.relname))
  from pg_class c where c.oid in ('private.cpsc_observation_payloads'::regclass,
    'private.cpsc_observation_sightings'::regclass);
select extensions.ok(has_function_privilege('service_role',
    'public.record_cpsc_retained_observation(text,text,text,text,text,date,text,timestamptz,text,jsonb)','EXECUTE')
  and not has_function_privilege('anon',
    'public.record_cpsc_retained_observation(text,text,text,text,text,date,text,timestamptz,text,jsonb)','EXECUTE')
  and not has_function_privilege('authenticated',
    'public.record_cpsc_retained_observation(text,text,text,text,text,date,text,timestamptz,text,jsonb)','EXECUTE'),
  'new worker RPC is service-role only');
select extensions.ok(not has_table_privilege(r, t, 'SELECT') and not has_table_privilege(r, t, 'INSERT'),
  format('%s cannot read or write %s', r, t))
  from unnest(array['anon','authenticated','service_role']) r,
    unnest(array['private.cpsc_observation_payloads','private.cpsc_observation_sightings',
      'private.cpsc_observation_payload_retention']) t;
select extensions.ok(not has_function_privilege(r, f, 'EXECUTE'), format('%s cannot execute %s', r, f))
  from unnest(array['anon','authenticated','service_role']) r,
    unnest(array['private.cpsc_attach_captured_payloads(jsonb,boolean)','private.cpsc_watermark_safety()',
      'private.cpsc_quarantine_evidence(uuid)']) f;
select extensions.ok(not has_function_privilege('service_role', f, 'EXECUTE'), format('worker cannot execute %s', f))
  from unnest(array['public.get_cpsc_quarantine_packet(uuid)',
    'public.reconcile_cpsc_quarantined_observation(uuid,text,text)']) f;
select extensions.is((select md5(p.prosrc) from pg_proc p
    where p.oid = 'public.record_cpsc_identity_observation(text,text,text,text,text,date,text,timestamptz,text)'::regprocedure),
  (select legacy_gate_md5 from v16a_before), 'legacy 9-argument gate body is unchanged');
select extensions.ok(has_function_privilege('service_role',
    'public.record_cpsc_identity_observation(text,text,text,text,text,date,text,timestamptz,text)','EXECUTE'),
  'legacy gate keeps its worker grant (deployed v3 worker stays compatible)');

-- The migration rewrites no production row.
select extensions.ok((select observations from v16a_before) = (select count(*) from private.cpsc_identity_observations)
  and (select observations_md5 from v16a_before) = (select md5(string_agg(o::text, '|' order by o.id)) from private.cpsc_identity_observations o),
  'observation rows unchanged by the migration');
select extensions.ok((select identities_md5 from v16a_before) = (select md5(string_agg(i::text, '|' order by i.id)) from private.cpsc_source_identities i)
  and (select aliases_md5 from v16a_before) = (select md5(string_agg(a::text, '|' order by a.id)) from private.cpsc_source_aliases a)
  and (select api_revisions_md5 from v16a_before) = (select md5(string_agg(r::text, '|' order by r.id)) from private.cpsc_api_revisions r)
  and (select notices_md5 from v16a_before) = (select md5(string_agg(n::text, '|' order by n.id)) from public.recall_notices n),
  'identities, aliases, API revisions, and notices unchanged by the migration');

-- Hash contract on real production payloads.
select extensions.is((select count(*) from public.recall_notices n
    where private.cpsc_payload_sha256_v1(n.raw_payload) is distinct from private.cpsc_canonical_json_sha256(n.raw_payload)),
  0::bigint, 'v1 hash equals the 16.12 hash on every production notice payload');
select extensions.ok((select count(*) from private.cpsc_identity_observations o
    join public.recall_notices n on n.external_id = o.upstream_api_id
      and private.cpsc_payload_recall_number(n.raw_payload) = o.official_recall_number
    where o.provenance like '%(stored notice)'
      and o.payload_hash = private.cpsc_payload_sha256_v1(n.raw_payload)) > 0
  and not exists (select 1 from private.cpsc_identity_observations o
    join public.recall_notices n on n.external_id = o.upstream_api_id
      and private.cpsc_payload_recall_number(n.raw_payload) = o.official_recall_number
    where o.provenance like '%(stored notice)'
      and o.payload_hash <> private.cpsc_payload_sha256_v1(n.raw_payload)),
  'v1 reproduces every hash the backfill recorded from stored notices');

-- Legacy treatment: the six production quarantines are hash-only and unsafe.
select extensions.is((select count(*) from private.cpsc_observation_payload_retention
    where resolution = 'quarantined' and payload_retention = 'legacy_hash_only'), 6::bigint,
  'six production quarantines are labelled legacy_hash_only');
select extensions.ok(not (private.cpsc_watermark_safety()->>'safe')::boolean, 'watermark safety is false before attachment');
select extensions.ok((select bool_and(exists (select 1 from jsonb_array_elements(private.cpsc_watermark_safety()->'unaccounted') u
    where u->>'apiId' = s.api and u->>'recallNumber' = s.num and u->>'payloadHash' = s.hash)) from v16a_six s)
  and jsonb_array_length(private.cpsc_watermark_safety()->'unaccounted') = 6,
  'unaccounted set is exactly the six known collisions');
select extensions.throws_ok($$select public.record_recall_source_sync_result('cpsc','success',
    '{"kind":"last_publish_date","value":"2026-12-31"}'::jsonb,null,'{}'::jsonb)$$,
  '23514', null, 'CPSC watermark advance is refused on production data');
select extensions.lives_ok($$select public.record_recall_source_sync_result('health_canada','success',
    (select watermark from private.recall_source_sync_state st join public.recall_sources s on s.id = st.source_id
      where s.source_key = 'health_canada'),null,'{}'::jsonb)$$,
  'Health Canada sync recording is unaffected');

-- Bounded attachment of the six captured payloads (rolled back).
create temporary table v16a_attach on commit drop as select $attach$${attachmentText}$attach$::jsonb as doc;
select extensions.is((private.cpsc_attach_captured_payloads((select doc from v16a_attach), false)->>'wouldAttach')::int, 6,
  'attachment dry run matches all six production quarantines');
select extensions.is((select count(*) from private.cpsc_observation_payloads), 0::bigint, 'dry run stores nothing');
select extensions.is((private.cpsc_attach_captured_payloads((select doc from v16a_attach), true)->>'attached')::int, 6,
  'attachment attaches six hash-verified payloads');
select extensions.is((private.cpsc_attach_captured_payloads((select doc from v16a_attach), true)->>'alreadyRetained')::int, 6,
  'attachment is idempotent');
select extensions.ok((private.cpsc_watermark_safety()->>'safe')::boolean, 'watermark safety holds after attachment');
select extensions.ok(e->'sourceRevision'->'payload' = item->'payload'
    and (e->'sourceRevision'->>'hashVerified')::boolean and e->>'payloadRetention' = 'retained'
    and exists (select 1 from jsonb_array_elements(e->'conflictingAliases') a
      where a->>'aliasKind' = 'api_id' and a->>'aliasValue' = item->>'apiId'
        and a->>'officialRecallNumber' <> item->>'recallNumber'),
  format('packet for %s carries the exact payload and the conflicting identity', item->>'recallNumber'))
  from v16a_attach, jsonb_array_elements(doc->'items') item,
    lateral (select private.cpsc_quarantine_evidence(o.id) e from private.cpsc_identity_observations o
      where o.resolution = 'quarantined' and o.upstream_api_id = item->>'apiId'
        and o.official_recall_number = item->>'recallNumber') packet;
select extensions.lives_ok($$select public.record_recall_source_sync_result('cpsc','success',
    '{"kind":"last_publish_date","value":"2026-12-31"}'::jsonb,null,'{}'::jsonb)$$,
  'CPSC watermark may advance once all quarantines are retained (rolled back)');
select extensions.ok((select count(*) from private.cpsc_identity_observations) = (select observations from v16a_before)
  and (select count(*) from private.cpsc_identity_reconciliations) = 0
  and (select count(*) from private.recall_scope_criteria_v2) = 0
  and (select historical_digest from v16a_before)
    = private.cpsc_historical_rows_digest((select id from public.recall_sources where source_key = 'cpsc')),
  'no observation, reconciliation, criterion, or historical row changed');

select * from extensions.finish();
rollback;
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await writeFile(OUTPUT, await buildSuite());
  console.log(JSON.stringify({ output: OUTPUT }));
}
